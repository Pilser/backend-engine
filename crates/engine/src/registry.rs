use serde_json::Value as Json;

#[derive(Debug, Clone)]
pub enum ArgType {
    Int,
    Str,
    Json,
    Path,
    Url,
    Seq,
    Name,
}

#[derive(Debug, Clone)]
pub struct ArgSpec {
    pub name: String,
    pub r#type: ArgType,
    pub required: bool,
    pub help: String,
}

#[derive(Debug, Clone)]
pub enum FlagType {
    Bool,
    Str,
    Int,
    Json,
    Path,
    Enum,
}

#[derive(Debug, Clone)]
pub struct FlagSpec {
    pub name: String,
    pub r#type: FlagType,
    pub default: Option<String>,
    pub allowed: Vec<String>,
    pub repeatable: bool,
    pub help: String,
    pub conflicts: Vec<String>,
    pub requires: Vec<String>,
}

#[derive(Debug, Clone)]
pub enum Role {
    Public,
    Reader,
    Writer,
    Admin,
    Owner,
}

#[derive(Debug, Clone)]
pub struct Example {
    pub args: String,
    pub description: String,
    pub response: Json,
}

#[derive(Debug, Clone)]
pub struct CommandSpec {
    pub group: String,
    pub verb: String,
    pub summary: String,
    pub description: String,
    pub positional: Vec<ArgSpec>,
    pub flags: Vec<FlagSpec>,
    pub body_json: Option<Json>,
    pub response: Json,
    pub auth: Role,
    pub destructive: bool,
    pub dry_run: bool,
    pub examples: Vec<Example>,
    pub see_also: Vec<String>,
    pub danger_notes: Option<String>,
}

impl CommandSpec {
    pub fn name(&self) -> String {
        format!("{}.{}", self.group, self.verb)
    }
}

